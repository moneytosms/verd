package relnotes

import "testing"

func TestLinesCleansAutoGeneratedNotes(t *testing.T) {
	body := "## Changelog\n* 3fd1342e5aa85723681e5bf1edb7460b7db5629e: feat: update toast (@moneytosms)\n* fix: `retry` **fast**\n\n\n**Full Changelog**: https://x\n"
	got := Lines(body)
	want := []Line{
		{"Changelog", true},
		{"• Update toast", false},
		{"• Retry fast", false},
	}
	if len(got) != len(want) {
		t.Fatalf("%+v", got)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("line %d: %+v want %+v", i, got[i], want[i])
		}
	}
}
